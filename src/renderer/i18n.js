const DICTS = { fr, en, he };
let current = 'fr';

export function setLang(code) {
  current = DICTS[code] ? code : 'fr';
  const info = langInfo();
  if (typeof document !== 'undefined') {
    document.documentElement.lang = info.code;
    document.documentElement.dir = info.dir;
  }
}
export const getLang = () => current;
export const langInfo = () => LANGS.find((l) => l.code === current) || LANGS[0];
export const locale = () => langInfo().locale;

/** Traduit une clé ; si une traduction manque, retombe sur le français, puis sur la clé elle-même. */
export function t(key, ...args) {
  const v = DICTS[current][key] ?? fr[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}
